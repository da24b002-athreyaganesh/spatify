@dataclass
class Q:
    """One query: its PromQL, what it computes (the comment line), and the series it gives.

    `names` lists the series' display names when the query splits by a label with known
    values; each gets its own colour and line style. A single-series query is named by
    its legend.
    """

    expr: str
    legend: str
    computes: str
    names: list[str] = field(default_factory=list)
    color: str | None = None
    style: str = "solid"
    right_axis: str | None = None  # a label puts this series on a right-hand axis
    right_unit: str | None = None
    from_a4: bool = False

    def target(self, ref: str, instant: bool) -> dict:
        header = A4_ATTRIBUTION if self.from_a4 else ATTRIBUTION
        return {
            "refId": ref,
            "datasource": DATASOURCE,
            "expr": f"{header}. Computes: {self.computes}\n{self.expr}",
            "legendFormat": self.legend,
            "instant": instant,
            "range": not instant,
        }

    def series(self) -> list[str]:
        return self.names or [self.legend]


def override(name: str, color: str, style: str | None = None, extra: list | None = None):
    properties = [{"id": "color", "value": {"mode": "fixed", "fixedColor": color}}]
    if style:
        properties.append({"id": "custom.lineStyle", "value": STYLES[style]})
    return {"matcher": {"id": "byName", "options": name}, "properties": properties + (extra or [])}


def thresholds(steps: list[tuple[float, str]], base: str = "transparent") -> dict:
    return {
        "mode": "absolute",
        "steps": [{"color": base, "value": None}]
        + [{"color": color, "value": value} for value, color in steps],
    }


def grid(x: int, y: int, w: int, h: int) -> dict:
    return {"x": x, "y": y, "w": w, "h": h}


def row(panel_id: int, title: str, y: int) -> dict:
    return {
        "type": "row",
        "id": panel_id,
        "title": title,
        "collapsed": False,
        "gridPos": grid(0, y, 24, 1),
        "panels": [],
    }


def timeseries(
    panel_id: int,
    title: str,
    story: str,
    queries: list[Q],
    unit: str,
    axis: str,
    pos: tuple[int, int, int, int],
    *,
    lo: float | None = 0,
    hi: float | None = None,
    lines: list[tuple[float, str]] | None = None,
    step: bool = False,
    decimals: int | None = None,
    soft_hi: float | None = None,
) -> dict:
    """A time series panel. `lines` draws dashed horizontal lines (alert thresholds);
    `step` draws a value that jumps (a version number) as steps, not slopes; `soft_hi` is
    the axis top unless the data goes higher (so an all-zero line keeps a sensible axis)."""
    overrides, n = [], 0
    for q in queries:
        for name in q.series():
            color, style = (q.color, q.style) if q.color else CYCLE[n]
            extra = []
            if q.right_axis:
                extra = [
                    {"id": "custom.axisPlacement", "value": "right"},
                    {"id": "custom.axisLabel", "value": f"{q.right_axis} (linear)"},
                    {"id": "unit", "value": q.right_unit},
                    {"id": "min", "value": 0},
                    {"id": "max"},
                ]
            overrides.append(override(name, color, style, extra))
            n += 1
    defaults = {
        "unit": unit,
        "color": {"mode": "fixed", "fixedColor": BLUE},
        "custom": {
            "axisLabel": f"{axis} (linear)",
            "axisPlacement": "auto",
            "drawStyle": "line",
            "lineInterpolation": "stepAfter" if step else "linear",
            "lineWidth": 2,
            "fillOpacity": 0,
            "showPoints": "auto",
            "pointSize": 5,
            "spanNulls": False,
            "scaleDistribution": {"type": "linear"},
            "thresholdsStyle": {"mode": "dashed" if lines else "off"},
        },
        "thresholds": thresholds(lines or []),
    }
    if lo is not None:
        defaults["min"] = lo
    if hi is not None:
        defaults["max"] = hi
    if decimals is not None:
        defaults["decimals"] = decimals
    if soft_hi is not None:
        defaults["custom"]["axisSoftMax"] = soft_hi
    return {
        "type": "timeseries",
        "id": panel_id,
        "title": title,
        "description": story,
        "datasource": DATASOURCE,
        "gridPos": grid(*pos),
        "targets": [q.target(chr(65 + i), instant=False) for i, q in enumerate(queries)],
        "fieldConfig": {"defaults": defaults, "overrides": overrides},
        "options": {
            "legend": {
                "showLegend": n > 1,
                "displayMode": "list",
                "placement": "bottom",
                "calcs": [],
            },
            "tooltip": {"mode": "multi", "sort": "none"},
        },  # fmt: skip
    }


UP_DOWN = [
    {"type": "value", "options": {
        "1": {"text": "▲ UP", "color": BLUE, "index": 0},
        "0": {"text": "▼ DOWN", "color": VERMILLION, "index": 1},
    }},
    {"type": "special", "options": {
        "match": "null", "result": {"text": "▼ no data", "color": VERMILLION, "index": 2},
    }},
]  # fmt: skip


def words(ok: str, bad: str, missing: str) -> list[dict]:
    """Value mappings for a 0/1 status: 0 is good, 1 is bad, nothing is `missing`."""
    return [
        {"type": "value", "options": {
            "0": {"text": f"✓ {ok}", "color": BLUE, "index": 0},
            "1": {"text": f"▲ {bad}", "color": VERMILLION, "index": 1},
        }},
        {"type": "special", "options": {
            "match": "null", "result": {"text": missing, "color": SKY, "index": 2},
        }},
    ]  # fmt: skip


def stat(
    panel_id: int,
    title: str,
    story: str,
    query: Q,
    unit: str,
    pos: tuple[int, int, int, int],
    *,
    mappings: list | None = None,
    text_mode: str = "auto",
    decimals: int | None = None,
    colors: dict[str, str] | None = None,
) -> dict:
    """A single-number tile. With `mappings`, the tile's colour and words say the status."""
    defaults = {
        "unit": unit,
        "color": {"mode": "fixed", "fixedColor": BLUE},
        "mappings": mappings or [],
        "thresholds": thresholds([], base=BLUE),
    }
    if decimals is not None:
        defaults["decimals"] = decimals
    return {
        "type": "stat",
        "id": panel_id,
        "title": title,
        "description": story,
        "datasource": DATASOURCE,
        "gridPos": grid(*pos),
        "targets": [query.target("A", instant=True)],
        "fieldConfig": {
            "defaults": defaults,
            "overrides": [override(n, c) for n, c in (colors or {}).items()],
        },
        "options": {
            "reduceOptions": {"calcs": ["lastNotNull"], "fields": "", "values": False},
            "colorMode": "background" if mappings else "value",
            "graphMode": "none",
            "textMode": text_mode,
            "justifyMode": "auto",
            "orientation": "auto",
            "wideLayout": True,
        },
    }


def bargauge(
    panel_id: int,
    title: str,
    story: str,
    query: Q,
    unit: str,
    pos: tuple[int, int, int, int],
    *,
    hi: float | None = None,
    levels: list[tuple[float, str]] | None = None,
    decimals: int | None = None,
) -> dict:
    """Horizontal bars, one per series, each labelled: for series that come and go (model
    versions, triggers). One colour, or blue/orange/vermillion `levels` by value."""
    defaults = {
        "unit": unit,
        "min": 0,
        "color": {"mode": "thresholds" if levels else "fixed", "fixedColor": BLUE},
        "thresholds": thresholds(levels or [], base=BLUE),
    }
    if hi is not None:
        defaults["max"] = hi
    if decimals is not None:
        defaults["decimals"] = decimals
    return {
        "type": "bargauge",
        "id": panel_id,
        "title": title,
        "description": story,
        "datasource": DATASOURCE,
        "gridPos": grid(*pos),
        "targets": [query.target("A", instant=True)],
        "fieldConfig": {"defaults": defaults, "overrides": []},
        "options": {
            "orientation": "horizontal",
            "displayMode": "basic",
            "valueMode": "color",
            "namePlacement": "left",
            "showUnfilled": True,
            "sizing": "auto",
            "minVizHeight": 16,
            "minVizWidth": 8,
            "reduceOptions": {"calcs": ["lastNotNull"], "fields": "", "values": False},
        },
    }


def dashboard(uid: str, title: str, story: str, panels: list[dict]) -> dict:
    return {
        "uid": uid,
        "title": title,
        "description": story,
        "tags": ["spatify"],
        "timezone": "browser",
        "refresh": "10s",
        "time": {"from": "now-30m", "to": "now"},
        "schemaVersion": 39,
        "version": 1,
        "editable": False,
        "graphTooltip": 1,  # a shared crosshair across panels
        "links": [
            {
                "type": "dashboards",
                "tags": ["spatify"],
                "asDropdown": False,
                "title": "Spatify dashboards",
                "keepTime": True,
                "includeVars": False,
            }
        ],  # fmt: skip
        "annotations": {"list": []},
        "templating": {"list": []},
        "panels": panels,
    }


def up(job: str) -> Q:
    return Q(f'up{{job="{job}"}}', job, f"1 if Prometheus's last scrape of {job} worked, else 0")


