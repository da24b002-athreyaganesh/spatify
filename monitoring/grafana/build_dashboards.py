"""Builds Spatify's Grafana dashboards from the panel specs below (D42).

    uv run python monitoring/grafana/build_dashboards.py

writes monitoring/grafana/dashboards/{service,model,data,host}.json, which Grafana loads
into its "Spatify" folder. Edit this file, not the JSON: tests/test_monitoring.py fails if
the JSON is out of date, or if a query names a metric that nothing exports.

Every panel follows A4's "7 commandments" the same way:
1. Colour-blind-safe colours: Okabe-Ito only, and status tiles say UP/DOWN in words.
2. Markers that survive any medium: series sharing a panel also differ by line style.
3. Named axes: every time series has a y-axis label; the x axis is local time.
4. Explicit scale and units: a unit on every panel, and the axis label says "linear".
5. A legend whenever a panel has more than one series.
6. A title on every panel; rows act as section headings.
7. A short story: every panel has a description (the (i) next to its title).

AI attribution (course code of conduct, fair use of AI): every PromQL query below was
generated by Claude Opus 5.5 (Claude Code) on 2026-11-15; the two marked "from A4" date
from 2026-10-17. In the JSON, each query starts with a "# AI-generated PromQL" comment line
saying what it computes (PromQL ignores everything after #).
"""

